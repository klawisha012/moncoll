export const translations: Record<Lang, TranslationDict> = { en, ru };

export function t(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const raw = translations[lang]?.[key] ?? translations.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_m, name) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}
