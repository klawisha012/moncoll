func TestSignVerifyShortLived_RoundTrip(t *testing.T) {
	iss := testIssuer()

	payload := map[string]any{"email": "user@example.com", "code": "abc123"}
	tok, err := iss.SignShortLived(payload, 5*time.Minute, "verify_email")
	require.NoError(t, err)

	got, err := iss.VerifyShortLived(tok, "verify_email")
	require.NoError(t, err)

	assert.Equal(t, "user@example.com", got["email"])
	assert.Equal(t, "abc123", got["code"])
	// p and exp must be stripped
	assert.NotContains(t, got, "p")
	assert.NotContains(t, got, "exp")
}

func TestSignVerifyShortLived_WrongPurposeRejected(t *testing.T) {
	iss := testIssuer()

	tok, err := iss.SignShortLived(map[string]any{"x": 1}, time.Minute, "reset_password")
	require.NoError(t, err)

	_, err = iss.VerifyShortLived(tok, "verify_email")
	require.ErrorIs(t, err, ErrInvalidShortLived)
}

func TestSignVerifyShortLived_ExpiredRejected(t *testing.T) {
	iss := testIssuer()

	tok, err := iss.SignShortLived(map[string]any{"x": 1}, -time.Second, "test_purpose")
	require.NoError(t, err)

	_, err = iss.VerifyShortLived(tok, "test_purpose")
	require.ErrorIs(t, err, ErrInvalidShortLived)
}

func TestSignVerifyShortLived_TamperedRejected(t *testing.T) {
	iss := testIssuer()

	tok, err := iss.SignShortLived(map[string]any{"x": 1}, time.Minute, "test_purpose")
	require.NoError(t, err)

	// Flip the last byte of the base64 string.
	b := []byte(tok)
	b[len(b)-1] ^= 0x01
	_, err = iss.VerifyShortLived(string(b), "test_purpose")
	require.ErrorIs(t, err, ErrInvalidShortLived)
}

func TestSignVerifyShortLived_WrongKeyRejected(t *testing.T) {
	iss := testIssuer()

	otherKey := make([]byte, 32)
	for i := range otherKey {
		otherKey[i] = 0xFF
	}
	other := NewIssuer(otherKey)

	tok, err := iss.SignShortLived(map[string]any{"x": 1}, time.Minute, "test_purpose")
	require.NoError(t, err)

	_, err = other.VerifyShortLived(tok, "test_purpose")
	require.ErrorIs(t, err, ErrInvalidShortLived)
}

