func TestCreateSessionToken_RoundTrip(t *testing.T) {
	iss := testIssuer()
	dec := testDecoder()

	tid := int64(42)
	tr := "owner"

	tok, err := iss.CreateSessionToken(7, "client", &tid, &tr)
	require.NoError(t, err)
	require.NotEmpty(t, tok)

	claims, err := dec.Decode(tok)
	require.NoError(t, err)

	assert.Equal(t, "7", claims.Sub)
	assert.Equal(t, "client", claims.PlatformRole)
	require.NotNil(t, claims.TenantID)
	assert.Equal(t, int64(42), *claims.TenantID)
	require.NotNil(t, claims.TenantRole)
	assert.Equal(t, "owner", *claims.TenantRole)

	// iat/exp must be in the past/future window
	now := float64(time.Now().UTC().Unix())
	assert.LessOrEqual(t, claims.Iat, now+1)
	assert.Greater(t, claims.Exp, now)
	assert.Less(t, claims.Exp, now+float64(sessionTTL.Seconds())+10)
}

