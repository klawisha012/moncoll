func TestHashVerifyPassword_RoundTrip(t *testing.T) {
	hash, err := HashPassword("correct-horse-battery-staple")
	require.NoError(t, err)
	assert.True(t, VerifyPassword("correct-horse-battery-staple", hash))
	assert.False(t, VerifyPassword("wrong-password", hash))
}

func TestVerifyPassword_EmptyHashReturnsFalse(t *testing.T) {
	assert.False(t, VerifyPassword("anything", ""))
}

func TestVerifyPassword_InvalidHashReturnsFalse(t *testing.T) {
	assert.False(t, VerifyPassword("anything", "not-a-hash"))
}

func TestVerifyPassword_72ByteTruncation(t *testing.T) {
	// passlib truncates at 72 bytes; both sides must agree.
	// Build a 73-byte password and a 72-byte prefix.
	plain73 := make([]byte, 73)
	for i := range plain73 {
		plain73[i] = 'a'
	}
	plain72 := string(plain73[:72])

	// Hash the 73-byte string; it should verify as the 72-byte prefix.
	hash, err := HashPassword(string(plain73))
	require.NoError(t, err)
	assert.True(t, VerifyPassword(string(plain73), hash))
	assert.True(t, VerifyPassword(plain72, hash), "72-byte prefix must match (passlib truncation)")
}

