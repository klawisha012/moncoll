func TestEncryptDecryptShortLived_RoundTrip(t *testing.T) {
	iss := testIssuer()

	payload := map[string]any{"user_id": float64(99), "action": "confirm_email"}
	tok, err := iss.EncryptShortLived(payload, 10*time.Minute, "verify_email")
	require.NoError(t, err)

	got, err := iss.DecryptShortLived(tok, "verify_email")
	require.NoError(t, err)

	assert.InDelta(t, float64(99), got["user_id"], 0.1)
	assert.Equal(t, "confirm_email", got["action"])
	assert.NotContains(t, got, "p")
	assert.NotContains(t, got, "exp")
}

