func TestCreateSessionToken_ExpiredNotAccepted(t *testing.T) {
	// We can't easily mint a token with a past exp via Issuer, but we can
	// verify the Decoder rejects the expired fixture from token_test.go.
	dec := testDecoder()
	expired := mintLocal(t, testKey(), `{"sub":"7","pr":"admin","exp":`+
		itoa(time.Now().Add(-time.Hour).Unix())+`.0}`)
	_, err := dec.Decode(expired)
	require.ErrorIs(t, err, ErrInvalidToken)
}

